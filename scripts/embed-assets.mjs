/**
 * Bundles the built app (dist/) into the Worker as modules, so a deploy is one
 * script upload. Writes worker/assets.generated.mjs; run after `vite build`.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const DIST = 'dist';
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
};

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else files.push(path);
  }
})(DIST);

const TEXT = new Set(['.html', '.js', '.css', '.svg', '.json', '.txt']);
const lines = [
  '// Generated by scripts/embed-assets.mjs. Do not edit.',
  'const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));',
  '',
  'export const FILES = {',
];
for (const file of files) {
  const route = `/${relative(DIST, file).split('\\').join('/')}`;
  const ext = extname(file);
  const raw = readFileSync(file);
  const body = TEXT.has(ext) ? JSON.stringify(raw.toString('utf8')) : `bytes(${JSON.stringify(raw.toString('base64'))})`;
  lines.push(`  ${JSON.stringify(route)}: { type: ${JSON.stringify(TYPES[ext] ?? 'application/octet-stream')}, immutable: ${route.startsWith('/assets/')}, body: ${body} },`);
}
lines.push('};', '');
writeFileSync('worker/assets.generated.mjs', lines.join('\n'));
console.log(`Embedded ${files.length} files from ${DIST}/ into the Worker.`);
